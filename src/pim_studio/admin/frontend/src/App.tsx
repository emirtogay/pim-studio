import { Routes, Route, Navigate } from 'react-router-dom'
import AppShell from './components/AppShell'
import { RequireAuth, RequireRole } from './components/RequireAuth'
import PageStub from './components/PageStub'
import Activity from './pages/Activity'
import Conflicts from './pages/Conflicts'
import Coverage from './pages/Coverage'
import Images from './pages/Images'
import Imports from './pages/Imports'
import Modules from './pages/Modules'
import Login from './pages/Login'
import ProductDetail from './pages/ProductDetail'
import Products from './pages/Products'
import SyncRuns from './pages/SyncRuns'
import Users from './pages/Users'
import WhatsNew from './pages/WhatsNew'

/**
 * Route table for the product-management module.
 *
 * Providers live in the entry point (`main.tsx`, or `preview-main.tsx` for the
 * dev harness) rather than here, so the same route table renders in both
 * without two AuthProviders fighting over the session.
 *
 * Pages arrive as `PageStub` and are replaced as their data layer lands —
 * stubs rather than mock data on purpose, because fake shapes drift from the
 * API and then quietly lie. Schedules is the one left.
 */
export default function App() {
  return (
    <>
      <Routes>
        {/* Public route — the only path that doesn't require a session. */}
        <Route path="login" element={<Login />} />

        {/* Every other route sits behind RequireAuth. */}
        <Route element={<RequireAuth />}>
          {/* The landing view after sign-in. Deliberately outside AppShell:
              you are choosing which module to enter, so rendering it inside
              one of them would answer the question before it is asked. */}
          <Route path="modules" element={<Modules />} />

          <Route element={<AppShell />}>
            {/* Overview is off.
                The go-live funnel shipped in 0.16.0 and did not earn its
                place: most of what it showed, Coverage already says — and
                says better, with fill rates and an owner split — while the
                part that was genuinely its own arrived as eight stages of
                bars with the synthesis left to the reader. A morning page
                that needs synthesising is not a morning page.
                It comes back as a briefing that states its conclusions. Until
                then this lands on Coverage, which is the page that answers
                the question today. The funnel itself keeps running: the CLI
                report, the extract and the nightly snapshot are all live, so
                the week of history that deltas need accrues while the page is
                away. See `pages/Overview.tsx`. */}
            <Route index element={<Navigate to="/coverage" replace />} />
            <Route path="products" element={<Products />} />
            <Route path="products/:modelColor" element={<ProductDetail />} />
            <Route path="coverage" element={<Coverage />} />

            {/* A module beside Coverage rather than an Admin page. It answers
                a standing question — which options have no photo, and what has
                been handed to Turkey — and is opened on a cadence, which is
                what the primary nav is for.

                Readable by anyone signed in, like Coverage: the counts are
                worth seeing whatever your role. Everything that *acts* —
                starting a run, replacing the cookie, marking a bundle sent —
                is developer-or-planning, enforced server-side in
                `admin/images_api.py` rather than by hiding the page. */}
            <Route path="images" element={<Images />} />

            {/* Target of the top-bar bell. Reads CHANGELOG.md via the parsed
                extract in public/demo/, regenerated by
                `python -m pim_studio.changelog` alongside each release. */}
            <Route path="whats-new" element={<WhatsNew />} />

            {/* Planning or developer: import backoffice exports. */}
            <Route element={<RequireRole allowed={['developer', 'planning']} />}>
              <Route path="admin/imports" element={<Imports />} />
              {/* A working queue, not an admin setting — same audience as
                  Imports: whoever is responsible for the content being right. */}
              <Route path="admin/conflicts" element={<Conflicts />} />
            </Route>

            {/* Developer only. */}
            <Route element={<RequireRole allowed={['developer']} />}>
              {/* Not a developer curiosity: it is the only page that answers
                  "is what I am looking at current", which every other page
                  quietly depends on. Kept under the developer gate for now
                  because acting on a stale sync means server access. */}
              <Route path="admin/runs" element={<SyncRuns />} />
              <Route
                path="admin/schedules"
                element={<PageStub title="Schedules" subtitle="Sync cadence" />}
              />
              {/* Accounts are shared with the price app — a role change here
                  changes it there. The page says so; see `Users.tsx`. */}
              <Route path="admin/users" element={<Users />} />
              {/* Reads the same log the Users page writes to, which is why the
                  two shipped together: an account page whose changes leave no
                  trace, and a trace nobody can read, are each half a feature. */}
              <Route path="admin/activity" element={<Activity />} />
            </Route>

            <Route path="*" element={<Navigate to="/" replace />} />
          </Route>
        </Route>
      </Routes>
    </>
  )
}
